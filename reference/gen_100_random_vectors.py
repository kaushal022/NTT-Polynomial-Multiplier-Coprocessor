#!/usr/bin/env python3

import os
import sys
import json
import random

sys.path.insert(0, os.path.dirname(__file__))
from mlkem_ntt_ref import (
    Q, N, N_INV, ZETAS,
    ntt_forward, ntt_inverse, basemul, multiply_ntts,
    poly_mul, poly_mul_schoolbook, random_poly
)

def main():
    random.seed(20261031)

    repo_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    vec_dir = os.path.join(repo_dir, "tb", "vectors", "random_100")
    sw_dir  = os.path.join(repo_dir, "software", "rv32_driver")
    os.makedirs(vec_dir, exist_ok=True)
    os.makedirs(sw_dir, exist_ok=True)

    NUM_VECTORS = 100
    print(f"Generating {NUM_VECTORS} random test vectors for ML-KEM NTT & PolyMul...")

    all_vectors = []
    flat_f = []
    flat_g = []
    flat_f_hat = []
    flat_g_hat = []
    flat_h_hat = []
    flat_h = []

    for k in range(NUM_VECTORS):
        f = random_poly()
        g = random_poly()

        f_hat = ntt_forward(f)
        g_hat = ntt_forward(g)

        f_rec = ntt_inverse(f_hat)
        assert f_rec == f, f"Vector {k}: NTT -> INTT round-trip failed!"

        g_rec = ntt_inverse(g_hat)
        assert g_rec == g, f"Vector {k}: NTT -> INTT round-trip failed for g!"

        h_hat = multiply_ntts(f_hat, g_hat)

        h = ntt_inverse(h_hat)

        h_school = poly_mul_schoolbook(f, g)
        assert h == h_school, f"Vector {k}: NTT multiplication did not match schoolbook!"

        all_vectors.append({
            "index": k,
            "f": f,
            "g": g,
            "f_hat": f_hat,
            "g_hat": g_hat,
            "h_hat": h_hat,
            "h": h
        })

        flat_f.extend(f)
        flat_g.extend(g)
        flat_f_hat.extend(f_hat)
        flat_g_hat.extend(g_hat)
        flat_h_hat.extend(h_hat)
        flat_h.extend(h)

        if (k + 1) % 20 == 0 or k == NUM_VECTORS - 1:
            print(f"  Generated {k + 1}/{NUM_VECTORS} vectors (cross-verified with schoolbook)...")

    json_path = os.path.join(vec_dir, "test_vectors_100.json")
    with open(json_path, "w") as jf:
        json.dump({
            "modulus": Q,
            "degree": N,
            "num_vectors": NUM_VECTORS,
            "vectors": all_vectors
        }, jf, indent=2)
    print(f"Saved JSON dataset: {json_path}")

    def save_hex(name, data):
        path = os.path.join(vec_dir, name)
        with open(path, "w") as hf:
            for val in data:
                hf.write(f"{val:03X}\n")
        return path

    save_hex("inputs_f.hex", flat_f)
    save_hex("inputs_g.hex", flat_g)
    save_hex("expected_f_hat.hex", flat_f_hat)
    save_hex("expected_g_hat.hex", flat_g_hat)
    save_hex("expected_h_hat.hex", flat_h_hat)
    save_hex("expected_h.hex", flat_h)
    print(f"Saved Verilog hex memory files in: {vec_dir}")

    c_header_path = os.path.join(sw_dir, "test_vectors_100.h")
    with open(c_header_path, "w") as ch:
        ch.write("/**\n")
        ch.write(" * =============================================================================\n")
        ch.write(" * ML-KEM Coprocessor Golden Test Vectors (100 Random Inputs)\n")
        ch.write(" * Generated by reference/gen_100_random_vectors.py\n")
        ch.write(" * Modulus: q = 3329, Degree: n = 256\n")
        ch.write(" * =============================================================================\n")
        ch.write(" */\n\n")
        ch.write("#ifndef TEST_VECTORS_100_H\n")
        ch.write("#define TEST_VECTORS_100_H\n\n")
        ch.write("#include <stdint.h>\n\n")
        ch.write(f"#define NUM_ONBOARD_TEST_VECTORS {NUM_VECTORS}\n\n")

        ch.write("// Golden checksums (sum of 256 coefficients mod 65536) for all 100 result polynomials h\n")
        ch.write(f"static const uint16_t g_golden_h_checksums[{NUM_VECTORS}] = {{\n    ")
        for i, vec in enumerate(all_vectors):
            csum = sum(vec["h"]) & 0xFFFF
            ch.write(f"0x{csum:04X}, ")
            if (i + 1) % 10 == 0 and i < NUM_VECTORS - 1:
                ch.write("\n    ")
        ch.write("\n};\n\n")

        EMBED_COUNT = 5
        ch.write(f"// First {EMBED_COUNT} full 256-word polynomial pairs for bit-by-bit validation\n")
        for i in range(EMBED_COUNT):
            vec = all_vectors[i]
            ch.write(f"static const uint16_t g_test_f_{i}[256] = {{\n    ")
            for j, val in enumerate(vec["f"]):
                ch.write(f"{val}, ")
                if (j + 1) % 16 == 0 and j < 255:
                    ch.write("\n    ")
            ch.write("\n};\n\n")

            ch.write(f"static const uint16_t g_test_g_{i}[256] = {{\n    ")
            for j, val in enumerate(vec["g"]):
                ch.write(f"{val}, ")
                if (j + 1) % 16 == 0 and j < 255:
                    ch.write("\n    ")
            ch.write("\n};\n\n")

            ch.write(f"static const uint16_t g_expected_h_{i}[256] = {{\n    ")
            for j, val in enumerate(vec["h"]):
                ch.write(f"{val}, ")
                if (j + 1) % 16 == 0 and j < 255:
                    ch.write("\n    ")
            ch.write("\n};\n\n")

        ch.write("#endif // TEST_VECTORS_100_H\n")

    print(f"Saved C on-board test header: {c_header_path}")
    print("\nAll 100 random test vectors successfully created and verified bit-exact!")

if __name__ == "__main__":
    main()
